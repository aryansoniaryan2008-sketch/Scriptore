-- Scriptora order intake and admin dashboard schema for Supabase.
-- Run once in Supabase Dashboard > SQL Editor. Do not put a service_role key in the site.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  phone text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.is_admin = true
  );
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_admin()));

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name, phone)
  values (
    new.id,
    new.email,
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    nullif(new.raw_user_meta_data ->> 'phone', '')
  )
  on conflict (id) do update set
    email = excluded.email,
    full_name = coalesce(public.profiles.full_name, excluded.full_name),
    phone = coalesce(public.profiles.phone, excluded.phone);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create sequence if not exists public.scriptora_order_number_seq;

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_no text unique,
  user_id uuid not null references auth.users(id) on delete restrict,
  email text not null,
  phone text not null,
  service text not null,
  pages integer not null check (pages between 1 and 5000),
  requirements text not null,
  deadline date not null,
  fulfillment text not null check (fulfillment in ('pickup', 'delivery')),
  address text,
  pincode text,
  slot text not null,
  subtotal numeric(12,2) not null check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  delivery_fee numeric(12,2) not null default 0 check (delivery_fee >= 0),
  total numeric(12,2) not null check (total >= 0),
  referral_code text,
  consent boolean not null check (consent = true),
  whatsapp_opt_in boolean not null default false,
  status text not null default 'Order Received'
    check (status in ('Order Received', 'Under Review', 'Payment Pending', 'Confirmed', 'Processing', 'Quality Check', 'Ready', 'Completed', 'Cancelled', 'Refunded')),
  paid boolean not null default false,
  status_history jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((fulfillment = 'pickup') or (address is not null and pincode is not null))
);

create index if not exists orders_user_created_idx on public.orders (user_id, created_at desc);
create index if not exists orders_status_created_idx on public.orders (status, created_at desc);

create or replace function public.prepare_scriptora_order()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if new.order_no is null then
      new.order_no := 'SCR-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('public.scriptora_order_number_seq')::text, 4, '0');
    end if;
    new.status_history := jsonb_build_array(jsonb_build_object('status', new.status, 'at', now()));
    new.updated_at := now();
  elsif new.status is distinct from old.status then
    new.status_history := coalesce(old.status_history, '[]'::jsonb)
      || jsonb_build_array(jsonb_build_object('status', new.status, 'at', now()));
    new.updated_at := now();
  end if;
  return new;
end;
$$;

drop trigger if exists prepare_scriptora_order on public.orders;
create trigger prepare_scriptora_order
before insert or update of status on public.orders
for each row execute function public.prepare_scriptora_order();

alter table public.orders enable row level security;
drop policy if exists "Customers can create their own orders" on public.orders;
create policy "Customers can create their own orders"
  on public.orders for insert to authenticated
  with check (user_id = (select auth.uid()) and consent = true);
drop policy if exists "Customers and admins can read orders" on public.orders;
create policy "Customers and admins can read orders"
  on public.orders for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin()));
drop policy if exists "Admins can update orders" on public.orders;
create policy "Admins can update orders"
  on public.orders for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

-- Public tracking reveals only the status and fulfillment details after both
-- the hard-to-guess order number and matching customer phone/email are supplied.
create or replace function public.track_order(p_order_no text, p_contact text)
returns table(order_no text, status text, fulfillment text, created_at timestamptz, history jsonb)
language sql
stable
security definer
set search_path = ''
as $$
  select o.order_no, o.status, o.fulfillment, o.created_at, o.status_history as history
  from public.orders o
  where upper(o.order_no) = upper(trim(p_order_no))
    and (
      lower(o.email) = lower(trim(p_contact))
      or regexp_replace(o.phone, '\D', '', 'g') = regexp_replace(trim(p_contact), '\D', '', 'g')
    )
  limit 1;
$$;
revoke all on function public.track_order(text, text) from public;
grant execute on function public.track_order(text, text) to anon, authenticated;

-- The existing portal queries these tables for customer balances and the
-- admin's payout-request panel; keep them present even before creator features
-- are enabled.
create table if not exists public.credit_balance (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance numeric(12,2) not null default 0 check (balance >= 0)
);
alter table public.credit_balance enable row level security;
drop policy if exists "Users can read their own credit balance" on public.credit_balance;
create policy "Users can read their own credit balance"
  on public.credit_balance for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin()));

create table if not exists public.payout_requests (
  id bigint generated by default as identity primary key,
  creator_id uuid not null references auth.users(id) on delete cascade,
  amount numeric(12,2) not null check (amount > 0),
  upi_id text not null,
  status text not null default 'requested' check (status in ('requested', 'paid', 'rejected')),
  requested_at timestamptz not null default now(),
  paid_at timestamptz
);
alter table public.payout_requests enable row level security;
drop policy if exists "Creators and admins can read payout requests" on public.payout_requests;
create policy "Creators and admins can read payout requests"
  on public.payout_requests for select to authenticated
  using (creator_id = (select auth.uid()) or (select public.is_admin()));
drop policy if exists "Admins can update payout requests" on public.payout_requests;
create policy "Admins can update payout requests"
  on public.payout_requests for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

-- Order uploads are private. The existing portal uploads to a folder named
-- with the signed-in user's UUID and creates short-lived signed URLs for admins.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('order-files', 'order-files', false, 10485760,
  array['application/pdf', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', 'image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set public = false, file_size_limit = 10485760;

drop policy if exists "Customers can upload files to their own folder" on storage.objects;
create policy "Customers can upload files to their own folder"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'order-files' and (storage.foldername(name))[1] = (select auth.uid())::text);
drop policy if exists "Admins can read order files" on storage.objects;
create policy "Admins can read order files"
  on storage.objects for select to authenticated
  using (bucket_id = 'order-files' and (select public.is_admin()));

